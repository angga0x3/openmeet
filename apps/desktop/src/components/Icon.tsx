export type IconName = keyof typeof icons;

export function Icon({
  name,
  size = 16,
  className,
  strokeWidth = 1.75,
}: {
  name: IconName;
  size?: number;
  className?: string;
  strokeWidth?: number;
}) {
  const Component = icons[name] as ComponentType<LucideProps>;
  return <Component size={size} className={className} strokeWidth={strokeWidth} aria-hidden />;
}
